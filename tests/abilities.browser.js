import Phaser from 'phaser';
import { gameConfig } from '../src/config/gameConfig';
import { CharacterUnlockService } from '../src/systems/CharacterUnlockService';
import { CHARACTER_CODES } from '../src/config/CharacterUnlockConfig';
import { SpecialAbilityConfig as config } from '../src/config/SpecialAbilityConfig';
import { Enemy } from '../src/entities/enemies/Enemy';
import { Projectile } from '../src/entities/Projectile';
import { CombatEvents } from '../src/systems/CombatEvents';

const checks = [];
const check = (name, value) => { if (!value) throw new Error(name); checks.push(name); };
window.abilityResults = { status: 'running' };
const game = new Phaser.Game({ ...gameConfig, type: Phaser.CANVAS, scale: { mode: Phaser.Scale.NONE },
    scene: [{ key: 'AbilityTestBoot', create() {
        const unlocks = new CharacterUnlockService(() => ({ getItem: () => null, setItem() {} }));
        for (const code of Object.values(CHARACTER_CODES)) unlocks.redeem(code);
        this.game.registry.set('character-unlock-service', unlocks);
        this.scene.start('GameScene', { character: 'lua' });
    } }, ...gameConfig.scene] });
window.abilityGame = game;
let now = 1000;
const tick = (n = 1) => { for (let i = 0; i < n; i++) game.scene.update(now += 1000 / 60, 1000 / 60); };
const reset = (sprite, x, y) => sprite.body.reset(x, y);
async function run() {
    while (!game.scene.isActive('GameScene')) await new Promise(r => setTimeout(r, 20));
    game.loop.sleep();
    let scene = game.scene.getScene('GameScene');
    scene.sys.sceneUpdate = () => {};
    const restart = character => {
        scene.scene.restart({ character }); tick(3);
        scene = game.scene.getScene('GameScene'); scene.sys.sceneUpdate = () => {};
    };
    let manager = scene.specialAbilities;
    let ability = manager.ability;
    const enemies = scene.enemyManager.getLivingEnemies();
    let clears = 0, deaths = 0;
    scene.events.on(CombatEvents.ROOM_CLEARED, () => clears++);
    enemies.forEach(e => e.on(CombatEvents.ENEMY_DIED, () => deaths++));
    check('Lua usa LuaSpecial', ability.constructor.name === 'LuaSpecial');
    check('Hojas originales cargadas: ocho frames por personaje', ['lua', 'alex'].every(c =>
        game.textures.get(`${c}-special`).getFrameNames().length === 8));
    check('Activación disponible', ability.activate());
    check('Activación repetida rechazada', !ability.activate());
    manager.update(config.lua.chargeMs - 1);
    check('Carga sin muerte prematura', scene.enemyManager.aliveCount === 2);
    check('Animación original y jugador físico intacto', manager.pose.visible && !scene.player.physicsSprite.visible && scene.player.physicsSprite.body.enable);
    scene.player.shootingKeys.UP.isDown = true;
    scene.player.update();
    check('No dispara arma normal durante especial', scene.player.consumeShootRequest() === null);
    scene.player.shootingKeys.UP.isDown = false;
    // A robot behind a solid wall must still be struck.
    reset(scene.player.physicsSprite, 224, 224); reset(enemies[0], 352, 224);
    check('Robot de prueba detrás de pared', !scene.lineOfSight.hasLineOfSight(scene.player, enemies[0]));
    manager.update(1);
    check('Descarga letal de habitación ignora paredes', scene.enemyManager.aliveCount === 0 && deaths === 2);
    check('ROOM_CLEARED único y jugador vivo', clears === 1 && !scene.player.isDead());
    check('Efecto eléctrico visible', manager.electricity.commandBuffer.length > 0);
    manager.update(config.lua.durationMs + config.lua.recoveryMs);
    check('Cooldown y restauración de sprite', ability.state === 'cooldown' && !manager.pose.visible && scene.player.physicsSprite.visible);
    check('Electricidad retirada sin nuevas muertes', manager.electricity.commandBuffer.length === 0 && deaths === 2 && clears === 1);
    check('Cooldown bloquea habilidad', !ability.activate());
    manager.update(config.lua.cooldownMs);
    check('Cooldown termina', ability.state === 'ready');
    ability.activate(); manager.update(config.lua.chargeMs);
    check('Habitación vacía permite descarga sin eventos duplicados', scene.enemyManager.aliveCount === 0 && clears === 1);
    const oldManager = manager;
    scene.changeRoom(); tick(3);
    scene = game.scene.getScene('GameScene'); scene.sys.sceneUpdate = () => {};
    const nextEnemy = new Enemy(scene, 352, 224, 'robot-red', { patrol: false });
    scene.enemyManager.add(nextEnemy);
    check('Cambio de habitación conserva Lua sin afectar nuevos enemigos', scene.character === 'lua' && scene.roomIndex === 1 && !nextEnemy.isDead());
    check('Habitación cancela y destruye habilidad anterior', oldManager.destroyed && !oldManager.pose.scene && !oldManager.electricity.scene);
    check('Cooldown conservado entre habitaciones', scene.specialAbilities.ability.state === 'cooldown' && !scene.specialAbilities.ability.activate());
    restart('lua'); manager = scene.specialAbilities; ability = manager.ability;
    ability.activate(); manager.update(200); scene.player.die();
    const survivors = scene.enemyManager.aliveCount;
    manager.update(1000);
    check('Muerte durante carga cancela descarga', scene.enemyManager.aliveCount === survivors && !ability.performing && !manager.pose.visible);
    check('Jugador muerto no puede reactivar', !ability.activate());
    check('Derrota visible, cuerpo desactivado', scene.player.physicsSprite.visible && !scene.player.physicsSprite.body.enable && scene.player.physicsSprite.anims.currentAnim.key.includes('defeat'));
    restart('lua'); manager = scene.specialAbilities; ability = manager.ability;
    ability.activate(); manager.update(config.lua.chargeMs); scene.player.die(); manager.update(500);
    check('Muerte durante descarga retira electricidad y conserva derrota', !manager.pose.visible && manager.electricity.commandBuffer.length === 0 && scene.player.physicsSprite.visible);
    restart('alex'); manager = scene.specialAbilities; ability = manager.ability;
    check('Alex usa AlexSpecial', ability.constructor.name === 'AlexSpecial');
    const alexEnemies = scene.enemyManager.getLivingEnemies();
    let alexClears = 0, alexDeaths = 0;
    scene.events.on(CombatEvents.ROOM_CLEARED, () => alexClears++);
    alexEnemies.forEach(e => e.on(CombatEvents.ENEMY_DIED, () => alexDeaths++));
    reset(scene.player.physicsSprite, 224, 224); reset(alexEnemies[0], 352, 224);
    check('Alex: robot protegido por pared antes de activar', !scene.lineOfSight.hasLineOfSight(scene.player, alexEnemies[0]));
    ability.activate(); manager.update(config.alex.chargeMs - 1);
    check('Alex respeta carga antes de eliminar enemigos', scene.enemyManager.aliveCount === 2);
    const impactTargets = alexEnemies.map(e => ({ x: e.x, y: e.y }));
    manager.update(1);
    check('Alex elimina todos los enemigos de la habitación pese a las paredes', scene.enemyManager.aliveCount === 0 && alexEnemies.every(e => e.isDead()));
    check('Alex emite una muerte por robot y un solo ROOM_CLEARED', alexDeaths === 2 && alexClears === 1);
    check('Bolas verdes aparecen en posiciones de los enemigos', JSON.stringify(manager.impactPositions) === JSON.stringify(impactTargets) && manager.electricity.commandBuffer.length > 0);
    check('Especial no crea proyectiles físicos', scene.playerProjectiles.getLength() === 0);
    check('Alex conserva animación de metralleta', manager.pose.visible && manager.pose.texture.key === 'alex-special' && !scene.player.physicsSprite.visible);
    manager.update(100);
    check('Impactos permanecen fijos y no salen desde Alex', JSON.stringify(manager.impactPositions) === JSON.stringify(impactTargets) && scene.playerProjectiles.getLength() === 0);
    check('Animación de metralleta avanza', manager.pose.frame.name === '4');
    manager.update(config.alex.impactMs);
    check('Impactos verdes expiran sin objetos ni proyectiles', manager.impactPositions.length === 0 && manager.electricity.commandBuffer.length === 0 && scene.playerProjectiles.getLength() === 0);
    check('Reactivación durante ráfaga rechazada', !ability.activate());
    scene.player.wasd.D.isDown = true; scene.player.update();
    check('Movimiento disponible durante especial', scene.player.physicsSprite.body.velocity.x > 0);
    scene.player.wasd.D.isDown = false; scene.player.update();
    check('Ráfaga no daña a Alex', !scene.player.isDead());
    manager.update(config.alex.durationMs + config.alex.recoveryMs);
    check('Alex restaura arma y entra en cooldown', ability.state === 'cooldown' && scene.player.physicsSprite.visible && !manager.pose.visible);
    scene.player.shootingKeys.UP.isDown = true; scene.player.update();
    check('Disparo normal restaurado', scene.player.consumeShootRequest() !== null);
    scene.player.shootingKeys.UP.isDown = false;
    manager.update(config.alex.cooldownMs); ability.activate(); manager.update(config.alex.chargeMs);
    check('Alex puede usar especial en habitación vacía sin repetir muertes', alexDeaths === 2 && alexClears === 1 && !scene.player.isDead());
    check('Habitación vacía no genera bolas verdes', manager.impactPositions.length === 0 && manager.electricity.commandBuffer.length === 0);
    new Projectile(scene, scene.player.x, scene.player.y, new Phaser.Math.Vector2(0, -1), 'player', scene.playerProjectiles);
    const liveShots = [...scene.playerProjectiles.getChildren()];
    scene.player.die();
    check('Muerte en ráfaga limpia proyectiles y efecto', scene.playerProjectiles.getLength() === 0 && liveShots.every(s => !s.active) && !manager.pose.visible);
    restart('alex'); manager = scene.specialAbilities; ability = manager.ability;
    ability.activate(); manager.update(config.alex.chargeMs);
    check('Impactos nuevos visibles antes de reiniciar', manager.impactPositions.length === 2 && manager.electricity.commandBuffer.length > 0);
    new Projectile(scene, scene.player.x, scene.player.y, new Phaser.Math.Vector2(0, -1), 'player', scene.playerProjectiles);
    const beforeRestart = [...scene.playerProjectiles.getChildren()]; const old = manager;
    restart('alex');
    check('Reinicio limpia objetos anteriores', old.destroyed && beforeRestart.every(s => !s.active) && !old.pose.scene && old.impactPositions.length === 0 && !old.electricity.scene);
    check('Reinicio comienza listo y con un solo jugador', scene.specialAbilities.ability.state === 'ready' && scene.children.list.filter(c => c.texture?.key === 'alex-walk').length === 1);
    const oldShots = scene.playerProjectiles.getLength(); old.update(10000);
    check('Manager destruido no vuelve a disparar', scene.playerProjectiles.getLength() === oldShots);
    scene.specialAbilities.ability.activate(); scene.specialAbilities.update(config.alex.chargeMs);
    new Projectile(scene, scene.player.x, scene.player.y, new Phaser.Math.Vector2(0, -1), 'player', scene.playerProjectiles);
    const roomShots = [...scene.playerProjectiles.getChildren()]; const roomManager = scene.specialAbilities;
    scene.changeRoom(); tick(3); scene = game.scene.getScene('GameScene'); scene.sys.sceneUpdate = () => {};
    check('Cambio de habitación durante ráfaga limpia proyectiles y manager', roomShots.every(s => !s.active) && roomManager.destroyed && roomManager.impactPositions.length === 0 && !roomManager.electricity.scene && scene.playerProjectiles.getLength() === 0);
    check('Alex conserva identidad y cooldown al cambiar habitación', scene.character === 'alex' && scene.specialAbilities.ability.state === 'cooldown');
    const otherRoomEnemy = new Enemy(scene, 352, 224, 'robot-red', { patrol: false });
    scene.enemyManager.add(otherRoomEnemy);
    roomManager.update(10000);
    check('Especial anterior de Alex no afecta robots de otra habitación', !otherRoomEnemy.isDead());
    restart('alex'); manager = scene.specialAbilities; ability = manager.ability;
    ability.activate(); manager.update(config.alex.chargeMs - 1); scene.player.die(); manager.update(1000);
    check('Muerte de Alex durante carga impide eliminación global', scene.enemyManager.aliveCount === 2 && !ability.activate());
    restart('alex');
    // Leave a safe live scene for native Q/held-key checks in the Node runner.
    scene.enemies.getChildren().forEach(e => { e.stop(); e.updateBehavior = () => null; });
    scene.sys.sceneUpdate = scene.update;
    reset(scene.player.physicsSprite, 160, 352);
    game.loop.wake();
    window.abilityResults = { status: 'passed', count: checks.length, checks };
}
run().catch(error => { window.abilityResults = { status: 'failed', checks, error: error.stack }; });
